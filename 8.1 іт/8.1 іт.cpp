// Дано літерний рядок, який містить послідовність символів s[0], ..., s[n], ...
// 1. Вияснити, чи є серед цих символів трійка сусідніх букв "OGO" або "AGA".
// 2. Замінити кожну трійку сусідніх букв "OGO" або "AGA" парою зірочок "**".

#define _CRT_SECURE_NO_WARNINGS // дозволяє використовувати strcpy без помилки-попередження
#include <iostream>
using namespace std;

bool Exist(const char* str) //функція перевіряє чи існують OGO та AGA
{
    for (int i = 0; str[i] != '\0'; i++) // i = номер літери; йдемо по рядку, поки не дійшли до його кінця ('\0')
        if ((str[i] == 'O' && str[i + 1] == 'G' && str[i + 2] == 'O') ||
            (str[i] == 'A' && str[i + 1] == 'G' && str[i + 2] == 'A')) // i + 1 не змінює i, воно перевіряє наступну букву
            return true;
    return false;
}

char* Change(char* str) // отримує рядок
{
    char* tmp = new char[strlen(str) + 1]; // створюємо в пам'яті тимчасовий рядок: стільки місць, скільки літер + 1 (strlen(str) рахує літери в рядку без '\0'  + 1 додаємо одне місце під '\0')
    char* t = tmp; // t - адреса місця в новому рядку, куди запишемо наступний символ (спочатку це початок tmp)
    int i = 0; // i - номер символу в старому рядку str, який зараз перевіряємо
    while (str[i] != '\0') // повторюємо, поки не дійшли до кінця старого рядка
    {
        if ((str[i] == 'O' && str[i + 1] == 'G' && str[i + 2] == 'O') ||
            (str[i] == 'A' && str[i + 1] == 'G' && str[i + 2] == 'A'))
        {
            *t++ = '*'; // 1) записати '*' у клітинку, куди показує t   2) після цього посунути t на наступну клітинку
            *t++ = '*'; // те саме: записати '*' і посунути t далі
            i += 3; // у старому рядку пропускаємо всі 3 літери трійки
        }
        else
            *t++ = str[i++]; // // якщо тут немає трійки OGO або AGA 1) взяти літеру str[i]  2) записати її туди, куди дивиться t  3) посунути і t, і i на одну клітинку вперед
    }
    *t = '\0'; // ставимо '\0' в кінці нового рядка, щоб було видно, де він закінчується
    strcpy(str, tmp); // копіюємо готовий результат з tmp назад у str
    return tmp; // повертаємо новий рядок
}

int main()
{
    char str[101]; // масив на 101 символ: 100 літер + 1 місце для '\0'
    cout << "Enter string:" << endl;
    cin.getline(str, 100); // читаємо з клавіатури цілий рядок разом з пробілами в str (не більше 99 символів)
    if (Exist(str)) // викликаємо Exist; якщо вона повернула true
        cout << "String contains OGO or AGA" << endl;
    else
        cout << "String does not contain OGO or AGA" << endl;
    char* result = Change(str); // викликаємо Change; result - адреса нового рядка, який вона повернула
    cout << "Modified string (param) : " << str << endl;
    cout << "Modified string (result): " << result << endl;
    delete[] result; // звільнення пам'яті

    return 0;
}